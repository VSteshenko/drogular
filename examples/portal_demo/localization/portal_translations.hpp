    std::string translate(
        const std::string& locale,
        const std::string& key
    ) const override {
        return get(locale, key);
    }

    std::string get(
        const std::string& locale,
        const std::string& key
    ) const {
        const auto localeFound =
            values_.find(locale);

        if (localeFound == values_.end()) {
            return fallback(key);
        }

        const auto keyFound =
            localeFound->second.find(key);

        if (keyFound == localeFound->second.end()) {
            return fallback(key);
        }

        return keyFound->second;
    }

private:
    std::string fallback(
        const std::string& key
    ) const {
        const auto english =
            values_.find("en");

        if (english == values_.end()) {
            return key;
        }

        const auto found =
            english->second.find(key);

        if (found == english->second.end()) {
            return key;
        }

        return found->second;
    }

